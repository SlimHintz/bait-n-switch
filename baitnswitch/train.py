"""Train, evaluate and export the clickbait model.

    uv run python -m baitnswitch.train

Splits 70/15/15 stratified by dataset and label. C and the decision threshold
are chosen on the validation split only; the test split is scored once, at
the end, by a model refit on train+validation. Writes:

    models/model.joblib, models/model.json   (for the API)
    extension/weights.json                    (for the browser extension)
    reports/metrics.json, reports/metrics.md  (numbers quoted in the README)
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import train_test_split

from .data import load_corpus
from .model import MODEL_DIR, Classifier, build_pipeline, export_weights

ROOT = Path(__file__).resolve().parent.parent
SEED = 42
C_GRID = [0.5, 1, 2, 4, 8, 16]
THRESHOLDS = np.round(np.arange(0.30, 0.71, 0.01), 2)


def split(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    strata = df["dataset"] + "-" + df["target"].astype(str)
    train, rest = train_test_split(df, test_size=0.30, random_state=SEED, stratify=strata)
    val, test = train_test_split(rest, test_size=0.50, random_state=SEED, stratify=strata.loc[rest.index])
    return train, val, test


def macro_f1(frame: pd.DataFrame, probs: np.ndarray, threshold: float) -> float:
    """Mean F1 over the three corpora, so the easy one can't dominate."""
    scores = [
        f1_score(g["target"], probs[frame.index.get_indexer(g.index)] >= threshold)
        for _, g in frame.groupby("dataset")
    ]
    return float(np.mean(scores))


def metrics(y: pd.Series, probs: np.ndarray, threshold: float) -> dict:
    pred = probs >= threshold
    return {
        "n": int(len(y)),
        "positive_rate": round(float(y.mean()), 3),
        "f1": round(f1_score(y, pred), 3),
        "precision": round(precision_score(y, pred), 3),
        "recall": round(recall_score(y, pred), 3),
        "roc_auc": round(roc_auc_score(y, probs), 3),
        "avg_precision": round(average_precision_score(y, probs), 3),
    }


def per_dataset(frame: pd.DataFrame, probs: np.ndarray, threshold: float) -> dict:
    out = {"all": metrics(frame["target"], probs, threshold)}
    for name, g in frame.groupby("dataset"):
        out[name] = metrics(g["target"], probs[frame.index.get_indexer(g.index)], threshold)
    return out


def tune(train: pd.DataFrame, val: pd.DataFrame) -> tuple[float, float, list[dict]]:
    trials = []
    for C in C_GRID:
        probs = build_pipeline(C=C).fit(train["text"], train["target"]).predict_proba(val["text"])[:, 1]
        best_t = max(THRESHOLDS, key=lambda t: macro_f1(val, probs, t))
        trials.append({"C": C, "threshold": float(best_t), "val_macro_f1": round(macro_f1(val, probs, best_t), 4)})
        print(f"  C={C:<5} best threshold {best_t:.2f}  val macro-F1 {trials[-1]['val_macro_f1']:.4f}")
    best = max(trials, key=lambda r: r["val_macro_f1"])
    return best["C"], best["threshold"], trials


def cross_dataset(df: pd.DataFrame, C: float) -> list[dict]:
    """Train on one corpus, test on another: does the model learn clickbait or publisher style?"""
    rows = []
    for source in ["chakraborty", "webis17"]:
        model = build_pipeline(C=C).fit(df.loc[df.dataset == source, "text"], df.loc[df.dataset == source, "target"])
        for target in ["chakraborty", "webis16", "webis17"]:
            if target == source:
                continue
            g = df[df.dataset == target]
            probs = model.predict_proba(g["text"])[:, 1]
            rows.append({"train": source, "test": target,
                         "f1": round(f1_score(g["target"], probs >= 0.5), 3),
                         "roc_auc": round(roc_auc_score(g["target"], probs), 3)})
    return rows


def write_markdown(report: dict, path: Path) -> None:
    lines = [
        "# Evaluation report",
        "",
        "Generated by `python -m baitnswitch.train`. Test split is 15% of the data, held out until the end.",
        "",
        f"Chosen on validation: C = {report['C']}, threshold = {report['threshold']}",
        "",
        "## Held-out test set",
        "",
        "| Dataset | n | Clickbait rate | F1 | Precision | Recall | ROC AUC | Avg precision |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, m in report["test"].items():
        lines.append(f"| {name} | {m['n']} | {m['positive_rate']} | {m['f1']} | {m['precision']} | "
                     f"{m['recall']} | {m['roc_auc']} | {m['avg_precision']} |")
    lines += ["", "## Cross-dataset generalization (threshold 0.5)", "",
              "| Train on | Test on | F1 | ROC AUC |", "|---|---|---:|---:|"]
    lines += [f"| {r['train']} | {r['test']} | {r['f1']} | {r['roc_auc']} |" for r in report["cross_dataset"]]
    lines += ["", "## Validation search", "", "| C | Best threshold | Val macro-F1 |", "|---:|---:|---:|"]
    lines += [f"| {t['C']} | {t['threshold']} | {t['val_macro_f1']} |" for t in report["tuning"]]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    df = load_corpus()
    print(f"Loaded {len(df)} examples:\n{df.groupby('dataset')['target'].agg(['size', 'mean']).round(3)}")
    train, val, test = split(df)

    print("Tuning on validation split...")
    C, threshold, trials = tune(train, val)

    final = Classifier(build_pipeline(C=C).fit(pd.concat([train, val])["text"], pd.concat([train, val])["target"]), threshold)
    test = test.reset_index(drop=True)
    report = {
        "C": C,
        "threshold": threshold,
        "tuning": trials,
        "test": per_dataset(test, final.probabilities(test["text"].tolist()), threshold),
        "cross_dataset": cross_dataset(df, C),
    }

    final.save(MODEL_DIR)
    export_weights(final, ROOT / "extension" / "weights.json")
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "metrics.json").write_text(json.dumps(report, indent=2) + "\n")
    write_markdown(report, ROOT / "reports" / "metrics.md")
    print((ROOT / "reports" / "metrics.md").read_text())


if __name__ == "__main__":
    main()
